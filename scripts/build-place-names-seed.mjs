#!/usr/bin/env node
// Writes supabase/seeds/place-names-v1.sql from src/data/us-cities.json (the
// bundled GeoNames list: [name, state, lat, lng, population]). Deterministic:
// tests/site-program-readiness.test.mjs regenerates it and compares bytes.
//
//   node --no-warnings scripts/build-place-names-seed.mjs [--check]
//
// Names are normalized as core_place_norm() / normPlace() do. Dropped: names
// under four characters, the drafter's common-word places (COMMON_WORD_PLACES),
// and duplicates within a state (the larger population kept).
import fs from "node:fs";
import crypto from "node:crypto";
import { COMMON_WORD_PLACES } from "../supabase/functions/post-drafter/lint.ts";

export const SOURCE = "src/data/us-cities.json";
export const SEED = "supabase/seeds/place-names-v1.sql";
export const normPlace = (s) =>
  s.toLowerCase().replace(/['’]/g, "").replace(/\bst\b\.?/g, "saint").replace(/[^a-z0-9]+/g, " ").trim();
const q = (s) => `'${s.replace(/'/g, "''")}'`;

export function buildSeed(raw) {
  const sha = crypto.createHash("sha256").update(raw).digest("hex");
  const rows = new Map();
  for (const [name, state, , , pop] of JSON.parse(raw)) {
    const norm = normPlace(name);
    if (norm.length < 4 || COMMON_WORD_PLACES.has(name) || !/^[A-Z]{2}$/.test(state)) continue;
    const key = `${norm}|${state}`;
    const prev = rows.get(key);
    if (!prev || pop > prev.pop) rows.set(key, { norm, state, name, pop: Math.max(0, Math.round(pop || 0)) });
  }
  const list = [...rows.values()].sort((a, b) => (a.norm < b.norm ? -1 : a.norm > b.norm ? 1 : a.state < b.state ? -1 : 1));
  const out = [
    "-- Place reference v1 for site_program_readiness (20261029200000). GENERATED by",
    "-- scripts/build-place-names-seed.mjs from " + SOURCE + "; do not edit by hand.",
    "-- A data step, not a migration: run it once as the owner after the migration.",
    "-- Idempotent: a source already loaded (same sha256) is a no-op. Public place",
    "-- names only; no client data.",
    `-- source sha256 ${sha}, ${list.length} names`,
    "do $$",
    "begin",
    `  if exists (select 1 from place_name_sources where source_sha256 = '${sha}') then`,
    "    raise notice 'place-names-v1 already loaded'; return;",
    "  end if;",
    `  insert into place_name_sources (source, source_sha256, names) values ('${SOURCE}', '${sha}', ${list.length});`,
    "  insert into place_names (norm, state, name, population) values",
  ];
  list.forEach((r, i) => out.push(`    (${q(r.norm)}, '${r.state}', ${q(r.name)}, ${r.pop})${i === list.length - 1 ? "" : ","}`));
  out.push("  on conflict (norm, state) do update set population = greatest(place_names.population, excluded.population);", "end $$;", "");
  return { sql: out.join("\n"), sha, count: list.length };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const { sql, sha, count } = buildSeed(fs.readFileSync(SOURCE, "utf8"));
  if (process.argv.includes("--check")) {
    const same = fs.existsSync(SEED) && fs.readFileSync(SEED, "utf8") === sql;
    console.log(same ? `${SEED} is current (${count} names, source ${sha})` : `${SEED} is stale: regenerate it`);
    process.exit(same ? 0 : 1);
  }
  fs.writeFileSync(SEED, sql);
  console.log(`wrote ${SEED}: ${count} names from ${SOURCE} (sha256 ${sha})`);
}
