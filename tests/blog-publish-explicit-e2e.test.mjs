// A Git host with real 40-hex SHAs and real trees.
function gitHost() {
  let n = 0;
  const commits = {}; const blobs = {};
  const seed = sha1("seed");
  commits[seed] = { files: { "compass-blog.json": JSON.stringify(CONTRACT), [POSTS]: EMPTY, "brands/acme/content/blog/index.ts": "export {}" }, parents: [], author: "Tom" };
  const refs = { [BRANCH]: seed, careers: sha1("careers") };
  commits[refs.careers] = { files: {}, parents: [], author: "Tom" };
  const trees = {}; // tree sha -> files
  const treeOf = (sha) => { const t = sha1(`tree:${sha}`); trees[t] = commits[sha].files; return t; };
  const writes = [];
  const json = (s, b) => new Response(JSON.stringify(b), { status: s, headers: { "content-type": "application/json" } });
  const fetch = async (url, init = {}) => {
    const u = new URL(String(url)); const method = (init.method ?? "GET").toUpperCase(); const body = init.body ? JSON.parse(init.body) : null;
    if (method !== "GET") writes.push({ method, path: u.pathname, body });
    const base = `/repos/${OWNER}/${NAME}`;
    if (u.pathname === base) return json(200, { id: 4242, html_url: `https://github.com/${OWNER}/${NAME}`, default_branch: "careers" });
    const rest = u.pathname.slice(base.length);
    let m;
    if ((m = rest.match(/^\/git\/ref\/heads\/(.+)$/))) { const s = refs[decodeURIComponent(m[1])]; return s ? json(200, { object: { sha: s } }) : json(404, {}); }
    if ((m = rest.match(/^\/git\/commits\/([0-9a-f]{40})$/)) && method === "GET") {
      const c = commits[m[1]]; return c ? json(200, { sha: m[1], tree: { sha: treeOf(m[1]) }, author: { name: c.author }, parents: c.parents.map((p) => ({ sha: p })), message: "x" }) : json(404, {});
    }
    if ((m = rest.match(/^\/git\/trees\/([0-9a-f]{40})$/)) && method === "GET") {
      const files = trees[m[1]] ?? {};
      return json(200, { tree: Object.entries(files).map(([path, c]) => { const s = sha1(`blob:${c}`); blobs[s] = c; return { path, type: "blob", sha: s, size: c.length }; }) });
    }
    if ((m = rest.match(/^\/git\/blobs\/([0-9a-f]{40})$/))) return json(200, { encoding: "base64", content: Buffer.from(blobs[m[1]]).toString("base64") });
    if (rest === "/git/blobs" && method === "POST") { const s = sha1(`b${++n}`); blobs[s] = Buffer.from(body.content, "base64").toString("latin1"); return json(201, { sha: s }); }
    if (rest === "/git/trees" && method === "POST") {
      const files = { ...(trees[body.base_tree] ?? {}) };
      for (const e of body.tree) { if (e.sha === null) delete files[e.path]; else files[e.path] = e.content ?? blobs[e.sha]; }
      const t = sha1(`t${++n}`); trees[t] = files; return json(201, { sha: t });
    }
    if (rest === "/git/commits" && method === "POST") { const s = sha1(`c${++n}`); commits[s] = { files: trees[body.tree], parents: body.parents, author: body.author?.name ?? "Compass CRM" }; return json(201, { sha: s }); }
    if ((m = rest.match(/^\/git\/refs\/heads\/(.+)$/)) && method === "PATCH") { refs[decodeURIComponent(m[1])] = body.sha; return json(200, { object: { sha: body.sha } }); }
    if ((m = rest.match(/^\/compare\//))) return json(404, {});
    return json(404, { message: `unhandled ${method} ${u.pathname}` });
  };
  return { fetch, refs, commits, writes };
}

// Vercel: an UNLINKED project. Nothing deploys on a push; a deployment exists
// only when someone POSTs one. The production alias follows the newest READY
// production deployment.
function vercelHost(git) {
  const deployments = [{ id: "dpl_release", target: "production", readyState: "READY", sha: git.refs[BRANCH], project: PROJECT }];
  const created = [];
  const json = (s, b) => new Response(JSON.stringify(b), { status: s, headers: { "content-type": "application/json" } });
  const view = (d) => ({ id: d.id, url: `${d.project}-${d.id}.vercel.app`, target: d.target, readyState: d.readyState, state: d.readyState, project: { id: "prj_x" },
    meta: { githubCommitSha: d.sha, githubCommitRef: BRANCH } });
  const production = () => [...deployments].reverse().find((d) => d.target === "production" && d.readyState === "READY" && d.project === PROJECT);
  const fetch = async (url, init = {}) => {
    const u = new URL(String(url)); const method = (init.method ?? "GET").toUpperCase(); const body = init.body ? JSON.parse(init.body) : null;
    if (u.pathname === `/v9/projects/${PROJECT}`) return json(200, { id: "prj_x", name: PROJECT });
    if (u.pathname === `/v13/deployments/${encodeURIComponent(`${PROJECT}.vercel.app`)}`) return json(200, view(production()));
    if (u.pathname === "/v6/deployments") return json(200, { deployments: deployments.filter((d) => d.sha === u.searchParams.get("sha")).map(view) });
    if (u.pathname === "/v13/deployments" && method === "POST") {
      created.push(body);
      const d = { id: `dpl_${created.length}`, target: body.target, readyState: "BUILDING", sha: body.gitSource.sha, project: body.project, polls: 0 };
      deployments.push(d); return json(200, view(d));
    }
    let m;
    if ((m = u.pathname.match(/^\/v13\/deployments\/(dpl_[^/]+)$/))) { const d = deployments.find((x) => x.id === m[1]); if (++d.polls >= 2) d.readyState = "READY"; return json(200, view(d)); }
    return json(404, { message: `unhandled vercel ${method} ${u.pathname}` });
  };
  return { fetch, created, production };
}

// The live site: renders the post from the commit production serves, the way
// the Foundation renderer does (H1, TL;DR, hero, blocks, title rule).
const rich = (t) => (typeof t === "string" ? t : t.map((x) => (typeof x === "string" ? x : x.type === "link" ? `<a href="${x.href}">${x.text}</a>` : `<${x.type}>${x.text}</${x.type}>`)).join(""));
const block = (b) => ({ h2: () => `<h2>${b.text}</h2>`, h3: () => `<h3>${b.text}</h3>`, p: () => `<p>${rich(b.text)}</p>`, quote: () => `<blockquote>${rich(b.text)}</blockquote>`,
  ul: () => `<ul>${b.items.map((i) => `<li>${rich(i)}</li>`).join("")}</ul>`, ol: () => `<ol>${b.items.map((i) => `<li>${rich(i)}</li>`).join("")}</ol>`,
  sources: () => `<h2>${b.heading ?? "Sources"}</h2><ol>${b.items.map((s) => `<li><a href="${s.href}">${s.label}</a>${s.note ? ` — ${s.note}` : ""}</li>`).join("")}</ol>` })[b.type]();
function liveSite(git, vercel, siteName) {
  return async (url) => {
    const files = git.commits[vercel.production().sha].files;
    const slug = new URL(url).pathname.replace(/^\/blog\//, "");
    const a = readCompassPosts(files[POSTS]).posts.find((p) => p.slug === slug);
    if (!a) return new Response("not found", { status: 404 });
    const title = foundationDocumentTitle(a.seo.title, siteName);
    const img = a.heroImage && files[`public${a.heroImage.src}`] ? `<img alt="${a.heroImage.alt}" width="${a.heroImage.width}" height="${a.heroImage.height}" src="${a.heroImage.src}"/>` : "";
    return new Response(`<html><head><title>${title}</title><meta property="og:site_name" content="${siteName}"/><meta property="og:title" content="${title}"/>`
      + `<link rel="canonical" href="${url}"/></head><body><h1>${a.title}</h1><article data-compass-release="${a.compass.release_hash}">`
      + `${a.tldr ? `<p><strong>TL;DR:</strong> ${a.tldr}</p>` : ""}${img}${a.body.map(block).join("")}</article></body></html>`);
  };
}

test("publisher → site-push (explicit release) → one production deployment of the commit → verified live", async () => {
  const git = gitHost();
  const vercel = vercelHost(git);
  const supabase = fakeSupabase({
    secrets: { SYNC_CRON_SECRET: "cron", GITHUB_TOKEN: "ghp_fake", VERCEL_TOKEN: "vt_fake" },
    tables: { clients: [{ id: draftRow().client_id, name: "Acme", website_url: SITE }],
      sites: [{ id: SITE_ID, client_id: draftRow().client_id, url: SITE, stack: "nextjs", controlled_by_compass: true, repo_url: `https://github.com/${OWNER}/${NAME}`, branch: BRANCH,
        vercel_project: PROJECT, work_mode: "new_build", content_adapter: "foundation_brand_content", content_paths: PATHS }] },
  });
  const sitePush = createSitePushHandler({ supabase, fetch: (url, init) => (String(url).includes("api.vercel.com") ? vercel.fetch(url, init) : git.fetch(url, init)),
    timing: { findMs: 200, settleMs: 200, pollMs: 5 } });
  const r = { ...draftRow(), ...structuredClone(GOOD_BLOG), version: 1, draft_id: DRAFT_ID, claims: [{ id: OC }], hero,
    destination: { site_id: SITE_ID, url: SITE, repo_url: `https://github.com/${OWNER}/${NAME}`, branch: BRANCH, controlled_by_compass: true,
      content_adapter: "foundation_brand_content", content_paths: PATHS } };
  r.brief = buildBlogBrief(lucas(), draftRow()).brief;
  delete r.id;
  const finishes = [];
  const pushErrors = [];
  const before = git.refs[BRANCH];
  const publish = createBlogPublisher({
    authorized: async () => true,
    claim: async () => ({ id: DRAFT_ID, lease_token: "t", status: "publishing", snapshot: r, release_hash: HASH, scheduled_at: "2026-11-20T16:00:00Z" }),
    resume: async () => { throw new Error("unused"); }, authorize: async () => {}, finish: async (...a) => { finishes.push(a); },
    input: async () => lucas(), pages: async () => [], heroImage: async () => bytes,
    sitePush: async (body) => {
      const out = await sitePush(new Request("https://fn/site-push", { method: "POST", headers: { "content-type": "application/json", "x-cron-secret": "cron" }, body: JSON.stringify(body) }));
      if (!out.ok) pushErrors.push(await out.clone().text());
      return out;
    },
    fetchLive: liveSite(git, vercel, "Acme Roofing"),
  });
  const res = await (await publish(new Request("https://fn/publish", { method: "POST", body: JSON.stringify({ publication_id: DRAFT_ID }) }))).json();
  assert.equal(res.status, "published", JSON.stringify({ res, pushErrors }));
  const sha = git.refs[BRANCH];
  assert.notEqual(sha, before);
  assert.equal(res.commit_sha, sha);
  assert.deepEqual(git.commits[sha].parents, [before], "one commit on the head production served");
  assert.ok(git.commits[sha].files[`public/blog/images/${r.slug}-${fileHash.slice(0, 12)}.webp`], "the hero rides in the same commit");
  assert.equal(git.writes.filter((w) => w.path.includes("/git/refs/heads/careers")).length, 0, "the careers branch is untouched");
  assert.deepEqual(vercel.created.map((b) => [b.project, b.target, b.gitSource.sha]), [[PROJECT, "production", sha]], "exactly one production deployment, of that commit");
  assert.equal(vercel.production().sha, sha);
  const evidence = finishes.at(-1)[3];
  assert.equal(evidence.live_verified, true);
  assert.equal(evidence.deployment_target, "production");
  assert.equal(evidence.transport.vercel.explicit_release, true);
  // Retrying the same publication writes and deploys nothing more.
  const again = await (await publish(new Request("https://fn/publish", { method: "POST", body: JSON.stringify({ publication_id: DRAFT_ID }) }))).json();
  assert.notEqual(again.status, "published");
  assert.equal(vercel.created.length, 1);
  assert.equal(git.refs[BRANCH], sha);
});
