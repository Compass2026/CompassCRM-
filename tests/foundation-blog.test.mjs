test("site-push: the posts file is an authorised content entry on the branch of record; pages and components are still refused", () => {
  const site = { branch: "claude/show-me-electrical-careers-k6km12", stack: "nextjs", work_mode: "upgrade_existing", controlled_by_compass: true, vercel_project: "x",
    content_adapter: "foundation_brand_content", content_paths: { adapter: "foundation_brand_content", brand: "showme", posts_file: "brands/showme/content/blog/compass-posts.ts" } };
  const base = (over) => ({ requestedBranch: site.branch, previewRequested: false, pullRequest: false, productionBranchHint: null, siteRow: site,
    repoDefaultBranch: "main", repoEmpty: false, headAuthorName: "Tom", filePaths: [], ...over });
  const ok = resolvePushPlan(base({ filePaths: ["brands/showme/content/blog/compass-posts.ts"] }));
  assert.equal(ok.refuse, null); assert.equal(ok.grant, "content_entry"); assert.equal(ok.deployTarget, "production"); assert.equal(ok.branch, site.branch);
  for (const filePaths of [["brands/showme/content/blog/new-post.ts"], ["app/blog/[slug]/page.tsx"], ["brands/showme/content/blog/compass-posts.ts", "content/blog/compass.ts"]]) {
    const p = resolvePushPlan(base({ filePaths }));
    assert.ok(p.refuse, filePaths.join()); assert.match(p.refuse.error, /not an authorised content entry/);
  }
  assert.ok(resolvePushPlan(base({ filePaths: ["brands/showme/content/blog/compass-posts.ts"], deletePaths: ["x.ts"] })).refuse);
  // new_build over someone else's head: the same entry is allowed, anything else goes to the side branch
  const nb = { ...site, branch: "main", work_mode: "new_build" };
  assert.equal(resolvePushPlan(base({ siteRow: nb, requestedBranch: "main", filePaths: ["brands/showme/content/blog/compass-posts.ts"] })).grant, "content_entry");
  assert.equal(resolvePushPlan(base({ siteRow: nb, requestedBranch: "main", filePaths: ["app/page.tsx"] })).branch, "compass/foundation-build");
  // without a recorded posts file there is no exception at all
  const none = resolvePushPlan(base({ siteRow: { ...site, content_paths: { adapter: "foundation_brand_content", brand: "showme" } }, filePaths: ["brands/showme/content/blog/compass-posts.ts"] }));
  assert.ok(none.refuse);
});

test("detection: the Foundation blog contract from compass-blog.json + brands/<brand>/content (real SME PR tree)", () => {
  const tree = JSON.parse(fixture("foundation-blog-tree.json"));
  const contract = { ...CONTRACT, brand: "showme", posts_file: "brands/showme/content/blog/compass-posts.ts" };
  const d = detectContentContract(tree, { brand: "showme" }, { registeredBrands: ["showme", "harbor-lane"], compassBlog: JSON.stringify(contract) });
  assert.equal(d.adapter, "foundation_brand_content");
  assert.equal(d.writable, true);
  assert.equal(d.paths.posts_file, "brands/showme/content/blog/compass-posts.ts");
  assert.equal(d.paths.blog_route, "/blog/{slug}");
  assert.equal(planMutation(d.adapter, "blog_post", d.paths).mode, "push");
  // without the file's content, or for another brand, blog posts stay pull requests
  assert.equal(detectContentContract(tree, { brand: "showme" }).paths.posts_file, undefined);
  const other = detectContentContract(tree, { brand: "showme" }, { compassBlog: { ...contract, brand: "harbor-lane" } });
  assert.equal(other.paths.posts_file, undefined);
  assert.ok(other.reasons.some((r) => /not the recorded brand/.test(r)));
  const missingFile = detectContentContract(tree.filter((p) => !p.endsWith("compass-posts.ts")), { brand: "showme" }, { compassBlog: contract });
  assert.equal(missingFile.paths.posts_file, undefined);
  assert.equal(detectContentContract(tree, { brand: "showme" }, { compassBlog: { ...contract, blocks: false } }).paths.posts_file, undefined);
  // the contract alone identifies the layout, but the brand is still never guessed
  const minimal = ["compass-blog.json", "brands/ridge/content/blog/compass-posts.ts", "brands/ridge/content/blog/index.ts"];
  const declared = detectContentContract(minimal, null, { compassBlog: { ...contract, brand: "ridge", posts_file: "brands/ridge/content/blog/compass-posts.ts" } });
  assert.equal(declared.adapter, "foundation_brand_content");
  assert.equal(declared.writable, false);
  const recorded = detectContentContract(minimal, { brand: "ridge" }, { compassBlog: { ...contract, brand: "ridge", posts_file: "brands/ridge/content/blog/compass-posts.ts" } });
  assert.equal(recorded.paths.posts_file, "brands/ridge/content/blog/compass-posts.ts");
});

