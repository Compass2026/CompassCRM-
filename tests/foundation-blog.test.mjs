test("create: one changed file (the posts file) against the read head, everything outside the markers byte-identical", () => {
  const r = release();
  assert.deepEqual(publicationPaths(r), ["compass-blog.json", POSTS]);
  const out = preparePublication(r, HASH, repo(), DATE);
  assert.equal(out.already_present, false);
  assert.equal(out.expected_head, "b".repeat(40));
  assert.equal(out.url, `${SITE}/blog/compass-publishing-test`);
  assert.equal(out.hero_src, null);
  assert.equal(out.tldr_mode, "body");
  assert.deepEqual(out.files.map((f) => f.path), [POSTS]);
  const file = readCompassPosts(out.files[0].content);
  assert.ok(out.files[0].content.startsWith(EMPTY.slice(0, EMPTY.indexOf("[]"))));
  assert.ok(out.files[0].content.endsWith("] /* compass:end */;\n"));
  const [a] = file.posts;
  assert.equal(a.slug, "compass-publishing-test");
  assert.equal(a.path, "/blog/compass-publishing-test");
  assert.equal(a.title, r.h1, "title is the approved H1");
  assert.equal(a.seo.description, r.meta_description);
  assert.equal(a.seo.title, r.meta_title, "the approved meta title is the SEO title");
  assert.notEqual(a.seo.title, a.title, "meta title and H1 stay distinct");
  assert.equal(a.excerpt, r.meta_description);
  assert.equal(a.publishedAt, DATE);
  assert.deepEqual(a.relatedServices, ["/services/residential"]);
  assert.deepEqual(a.compass, { release_hash: HASH, draft_id: r.draft_id, draft_version: 3, keyword_id: r.keyword_id });
  assert.equal(a.author, undefined, "no byline for Compass posts");
  assert.equal(a.image, undefined, "no hero: client photography only");
  // TL;DR once, as the first paragraph; the approved CTA closes the body.
  assert.deepEqual(a.body[0], { type: "p", text: [{ type: "strong", text: "TL;DR:" }, " This is a synthetic test summary. It is never published."] });
  assert.deepEqual(a.body.at(-1), { type: "p", text: [{ type: "link", text: "Send us the details", href: "/contact" }] });
  // appending keeps existing Compass posts untouched
  const second = preparePublication(release({ slug: "second-post" }), "sha256:" + "2".repeat(64), repo(out.files[0].content), DATE);
  const both = readCompassPosts(second.files[0].content).posts;
  assert.deepEqual(both[0], a);
  assert.equal(both[1].slug, "second-post");
});

