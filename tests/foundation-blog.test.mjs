test("the contract and the posts file are checked before any write", () => {
  for (const bad of [{ blocks: false }, { version: 2 }, { adapter: "json_blog" }, { keyword_provenance: false }, { seo_fields: false },
    { brand: "showme" }, { posts_file: "brands/harbor-lane/content/blog/other.ts" }, { blog_route: "/news/{slug}" }]) {
    assert.throws(() => preparePublication(release(), HASH, repo(EMPTY, [], { ...CONTRACT, ...bad }), DATE), undefined, JSON.stringify(bad));
  }
  const paths = release().destination.content_paths;
  for (const posts_file of ["brands/showme/content/blog/compass-posts.ts", "brands/harbor-lane/content/compass-posts.ts", "brands/harbor-lane/content/blog/index.ts", "brands/harbor-lane/content/blog/x.json", "../compass-posts.ts"]) {
    const r = release({ destination: { ...release().destination, content_paths: { ...paths, posts_file } } });
    assert.throws(() => publicationPaths(r), /posts file/, posts_file);
  }
  const noBrand = release({ destination: { ...release().destination, content_paths: { ...paths, brand: undefined } } });
  assert.throws(() => publicationPaths(noBrand), /brand/);
  // a posts file that is not the generated one, or unreadable, is never overwritten
  for (const content of ["export const compassPosts: Article[] = [];", EMPTY.replace("[]", "[1,"), EMPTY + "/* compass:begin */", EMPTY.replace("[] ", "{} ")]) {
    assert.throws(() => preparePublication(release(), HASH, repo(content), DATE), /no overwrite/, content);
  }
  const unread = repo(); delete unread.files[1].content;
  assert.throws(() => preparePublication(release(), HASH, unread, DATE), /could not be read/);
  assert.throws(() => preparePublication(release(), HASH, { ...repo(), branch: "other" }, DATE), /destination changed/);
});

