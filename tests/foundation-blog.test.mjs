test("Markdown → blocks: deterministic, own-host links root-relative, sources block, refusals for what blocks cannot express", () => {
  const md = "## Title one\n\nA [link](https://www.harbor-lane.example/services/residential?x=1#faq) and [out](https://example.org/a), **bold** and _em_ and *em2*.\nSecond line joins.\n\n### Sub\n\n- one\n- **two**\n\n1. first\n2) second\n\n## References\n\n- [Ref A](https://example.org/a)\n- [Ref B](https://example.org/b) — with a note";
  const blocks = markdownToBlocks(md, SITE);
  assert.deepEqual(blocks, [
    { type: "h2", text: "Title one" },
    { type: "p", text: ["A ", { type: "link", text: "link", href: "/services/residential?x=1#faq" }, " and ", { type: "link", text: "out", href: "https://example.org/a" }, ", ",
      { type: "strong", text: "bold" }, " and ", { type: "em", text: "em" }, " and ", { type: "em", text: "em2" }, ". Second line joins."] },
    { type: "h3", text: "Sub" },
    { type: "ul", items: ["one", [{ type: "strong", text: "two" }]] },
    { type: "ol", items: ["first", "second"] },
    { type: "sources", heading: "References", items: [{ label: "Ref A", href: "https://example.org/a" }, { label: "Ref B", href: "https://example.org/b", note: "with a note" }] },
  ]);
  assert.deepEqual(markdownToBlocks(md, SITE), blocks, "deterministic");
  assert.deepEqual(markdownToBlocks("> A quoted line\n> continues", SITE), [{ type: "quote", text: "A quoted line continues" }]);
  assert.deepEqual(markdownToBlocks("## Sources\n\n- Plain item", SITE), [{ type: "h2", text: "Sources" }, { type: "ul", items: ["Plain item"] }]);
  assert.equal(foundationHref("https://harbor-lane.example", SITE), "/");
  assert.equal(foundationHref("https://other.example/x", SITE), "https://other.example/x");
  assert.equal(parseInline("snake_case stays text", SITE), "snake_case stays text");
  for (const bad of [
    "See [x](http://harbor-lane.example/a).", "See [x](ftp://example.org/a).", "Use `code` here.", "An ![image](https://example.org/i.png)",
    "# Second H1", "#### Deep heading", "---", "| a | b |", "  - nested", "\tindented", "**[nested](https://example.org)**",
    "Unclosed **bold", "Escaped \\* star", "## Heading with [link](https://example.org)", "- item\ncontinued", "a * b",
  ]) assert.throws(() => markdownToBlocks(bad, SITE), undefined, bad);
  // the publisher refuses before conversion: non-https links never reach it
  assert.throws(() => preparePublication(release({ body_markdown: "## A\n\nSee [x](http://example.org/a)." }), HASH, repo(), DATE), /HTTPS/);
  assert.throws(() => preparePublication(release({ body_markdown: "## A\n\nUse `code`." }), HASH, repo(), DATE), /cannot express/);
});

test("verifyLiveArticle against a real Foundation build: the exact release verifies, any tamper fails", () => {
  const html = fixture("foundation-blog-page.html");
  const r = release(); const url = `${SITE}/blog/compass-publishing-test`;
  // The fixture is the fictional demonstration brand, which the Foundation
  // always serves noindex; a client brand with indexing allowed has no robots meta.
  assert.equal(verifyLiveArticle(html, r, HASH, url), false, "noindex is never verified");
  const live = html.replace(/<meta name="robots"[^>]*>/, "");
  assert.equal(verifyLiveArticle(live, r, HASH, url), true);
  // the rendered hrefs are root-relative; the absolute form is not on the page
  assert.ok(live.includes('href="/services/residential"') && !live.includes(`href="${SITE}/services/residential"`));
  assert.equal(verifyLiveArticle(live.replace("The CRM converts the approved Markdown.", "The CRM converts the changed Markdown."), r, HASH, url), false, "body line");
  assert.equal(verifyLiveArticle(live, r, "sha256:" + "f".repeat(64), url), false, "release marker");
  assert.equal(verifyLiveArticle(live.replaceAll('href="/services/residential"', 'href="/services/commercial"'), r, HASH, url), false, "internal link");
  assert.equal(verifyLiveArticle(live.replaceAll('href="/contact"', 'href="/about"'), r, HASH, url), false, "CTA link");
  assert.equal(verifyLiveArticle(live.replace(/<h1([^>]*)>Compass publishing test article/, "<h1$1>Another title"), r, HASH, url), false, "H1");
  assert.equal(verifyLiveArticle(live.replaceAll("general reference", "other note"), r, HASH, url), false, "sources note");
  assert.equal(verifyLiveArticle(live.replace(`href="${url}"`, 'href="https://harbor-lane.example/blog/other"'), r, HASH, url), false, "canonical");
  assert.equal(verifyLiveArticle(live.replace(/TL;DR:/, "Summary:"), r, HASH, url), false, "TL;DR label");
  // <title>, og:title and twitter:title follow the approved meta title (with the
  // site's " | <site name>" suffix while it fits in 60), while the H1 is the article title.
  assert.ok(live.includes("<title>Synthetic SEO Title Check | Harbor Lane Plumbing</title>"));
  assert.ok(live.includes('property="og:title" content="Synthetic SEO Title Check | Harbor Lane Plumbing"'));
  assert.ok(live.includes('name="twitter:title" content="Synthetic SEO Title Check | Harbor Lane Plumbing"'));
  assert.equal(verifyLiveArticle(live.replace(/<title>[^<]*<\/title>/, "<title>Compass publishing test article | Harbor Lane Plumbing</title>"), r, HASH, url), false, "<title>");
  assert.equal(verifyLiveArticle(live.replace(/<title>[^<]*<\/title>/, "<title>Synthetic SEO Title Check</title>"), r, HASH, url), false, "suffix dropped although it fits");
  assert.equal(verifyLiveArticle(live.replace(/(property="og:title" content=")[^"]*/, "$1Another title"), r, HASH, url), false, "og:title");
  assert.equal(verifyLiveArticle(live.replace(/(name="twitter:title" content=")[^"]*/, "$1Another title"), r, HASH, url), false, "twitter:title");
  assert.equal(verifyLiveArticle(live, { ...r, meta_title: "A different approved title" }, HASH, url), false, "another approved meta title");
  assert.equal(verifyLiveArticle(live.replace(/<\/title>/, "</title><title>Second</title>"), r, HASH, url), false, "exactly one <title>");
  // the expected lines are the visible block text
  assert.ok(blockLines(markdownToBlocks(r.body_markdown, SITE)).includes("Example reference — general reference"));
  // the same HTML judged as another adapter keeps the old absolute-href rule
  const lucas = { ...r, destination: { ...r.destination, content_adapter: "lucas_json" } };
  assert.equal(verifyLiveArticle(live, lucas, HASH, url), false, "existing adapters still require the approved absolute href");
});

